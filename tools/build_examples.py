#!/usr/bin/env python3
"""Rebuild the worked examples in examples/ with the engine, from their state.json, and check that they match.

  python3 tools/build_examples.py                  rebuild every example and write what changed
  python3 tools/build_examples.py --check          rebuild in a temporary folder; exit 1 if a committed file differs (writes nothing)
  python3 tools/build_examples.py devtool-dense    only these examples
  python3 tools/build_examples.py --png            also redraw preview.png (needs Playwright and Chrome; optional)

An example is any folder in examples/ with a state.json. Each is copied to a temporary folder without the files the engine
makes (MADE below), built there with `engine.py build`, and given a README whose numbers are read from the result. The rest
is carried over as it is: state.json and decisions.md (the record; the build refreshes only state.json's version stamp and
file hashes), DESIGN.md and PRODUCT.md (so notes in od:keep blocks survive), preview.png and anything a person added.
Writing copies that tree back, so a build that fails changes nothing. The build date in overview.html and the times in
build/artifact are ignored when comparing, and a file whose only change is one of them stays as committed.
"""
import argparse
import json
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EXAMPLES = ROOT / "examples"
ENGINE = ROOT / "skills" / "opendesigner" / "scripts" / "engine.py"
MADE = {"tokens", "build", "preview", "preview.html", "overview.html", "README.md"}  # what the build and this tool write
STAMPS = {"overview.html": [(re.compile(r"· built \d{4}-\d{2}-\d{2}"), "· built <date>")],
          "build/artifact/project/design-system.json": [(re.compile(r'"at": "[0-9T:-]+Z"'), '"at": "<time>"')]}


def examples(root, only=()):
    found = sorted(p.name for p in root.iterdir() if (p / "state.json").is_file())
    missing = sorted(set(only) - set(found))
    if missing:
        sys.exit(f"no example called {', '.join(missing)} in {root} (examples: {', '.join(found)})")
    return [n for n in found if not only or n in only]


def files(d):
    return {p.relative_to(d).as_posix(): p for p in sorted(d.rglob("*")) if p.is_file() and p.name != ".DS_Store"}


def same(rel, a, b):
    """True when two versions of a file match, ignoring the build date and artifact times."""
    x, y = a.read_bytes(), b.read_bytes()
    if x == y:
        return True
    if rel.endswith(".png"):  # a redrawn PNG can differ in bytes only; compare the pixels when Pillow is there
        try:
            from PIL import Image, ImageChops
        except ImportError:
            return False
        with Image.open(a) as i, Image.open(b) as j:
            return i.size == j.size and ImageChops.difference(i.convert("RGBA"), j.convert("RGBA")).getbbox() is None
    if rel not in STAMPS:
        return False
    x, y = x.decode("utf-8", "replace"), y.decode("utf-8", "replace")
    for pat, repl in STAMPS[rel]:
        x, y = pat.sub(repl, x), pat.sub(repl, y)
    return x == y


def rebuild(src, dest):
    """Copy one example without what the engine makes, build it there and write its README. Returns the engine's output."""
    shutil.copytree(src, dest, ignore=lambda d, names: [n for n in names if Path(d) == src and n in MADE])
    out = subprocess.run([sys.executable, str(ENGINE), "build", "--dir", str(dest)], capture_output=True, text=True)
    if out.returncode:
        raise RuntimeError(f"engine.py build failed for {src.name}:\n{out.stdout[-2000:]}{out.stderr[-2000:]}")
    write_readme(dest, src.name)
    return out.stdout


def write_readme(d, name):
    """README with numbers read back from the generated files, so it cannot drift from them."""
    meta = json.loads((d / "tokens" / "opendesigner.meta.json").read_text(encoding="utf-8"))
    state = json.loads((d / "state.json").read_text(encoding="utf-8"))
    val = subprocess.run([sys.executable, str(ENGINE), "validate", "--json", "--dir", str(d)], capture_output=True, text=True)
    rep = json.loads(val.stdout)
    t, sp, sh, mo, el = meta["type"], meta["space"], meta["shape"], meta["motion"], meta["elevation"]
    mode = meta["params"]["space.densityMode"]["value"]
    dens = meta["density"][mode]
    acc = meta["ramps"]["accent"]["light"]["hex"]
    title = state.get("name") or name
    exports = ", ".join(sorted(p.name for p in (d / "build").iterdir() if p.is_dir()))
    lines = [
        f"# {title}", "", f"![{title}: components in light and dark, generated by the engine](preview.png)", "",
        state.get("summary", ""), "",
        "**Dials:** " + " · ".join(f"{k} {v}" for k, v in meta["dials"].items()) + ".", "",
        "| What | Result |", "|---|---|",
        f"| Type | body {t['base']}px, ratio {t['ratio']}, sizes {', '.join(str(x) for x in t['sizes'])}; weights "
        + ", ".join(f"{k} {v}" for k, v in t["weights"].items()) + " |",
        f"| Space | {sp['unit']}px unit; default density {mode} (controls {dens['control']['sm']}/{dens['control']['md']}/"
        f"{dens['control']['lg']}px); hit areas " + ", ".join(f"{k} {v}px" for k, v in sp["targets"].items()) + " |",
        f"| Shape | control radius {sh['control']}, containers {sh['container']}px, focus ring {sh['focusWidth']}px |",
        f"| Depth | {el['model']} |",
        f"| Motion | medium {mo['durations']['medium']}ms, spring damping {mo['spatial']['dampingRatio']}"
        + (", motion off (reduced everywhere)" if mo.get("motionOff") else "") + " |",
        f"| Color | {meta['color']['scheme']} scheme, accent solid `{acc[8]}`, text minimum {meta['color']['textMin']}:1, "
        f"themes {', '.join(meta['modes'])} |",
        f"| Validation | {rep['errors']} errors, {rep['warnings']} warnings, {rep['advisories']} notes; "
        f"{rep['stats'].get('contrastPairs')} contrast pairs checked |",
        "", "**Files:** `state.json` (the input), `decisions.md` (why each choice), `tokens/` (DTCG 2025.10 + resolver, canonical), "
        f"`build/` ({exports}), `DESIGN.md`, `PRODUCT.md`, `overview.html` (the whole system on one page), `preview.html` "
        "and `preview/` (the visual templates, filled in).", "",
        f"**Rebuild:** `python3 tools/build_examples.py {name}` runs `engine.py build` on `state.json` and rewrites this README. "
        "`python3 tools/build_examples.py --check` fails when a committed file differs from what the engine makes now.",
        "", "The product is fictional; no real brand's identity is copied.", ""]
    (d / "README.md").write_text("\n".join(lines), encoding="utf-8")


def compare(committed, built):
    """What would change: (changed, added, removed) as paths relative to the example."""
    a, b = files(committed), files(built)
    changed = [r for r in sorted(a.keys() & b.keys()) if not same(r, a[r], b[r])]
    return changed, sorted(b.keys() - a.keys()), sorted(a.keys() - b.keys())


def sync(committed, built):
    """Make the committed example match the built one. A file is removed only when the build no longer makes it (the
    build started from a copy of everything but MADE, so a person's own files are always there)."""
    changed, added, removed = compare(committed, built)
    for r in changed + added:
        (committed / r).parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(built / r, committed / r)
    for r in removed:
        (committed / r).unlink()
    for d in sorted((p for p in committed.rglob("*") if p.is_dir()), key=lambda p: -len(p.parts)):
        if not any(d.iterdir()) and not (built / d.relative_to(committed)).exists():
            d.rmdir()
    return changed, added, removed


def png(d):
    """preview.png: the top of preview.html at 1280 x 1000, 1x, in Chrome (as the committed ones were made)."""
    from playwright.sync_api import sync_playwright
    with sync_playwright() as pw:
        b = pw.chromium.launch(channel="chrome")
        pg = b.new_page(viewport={"width": 1280, "height": 1000}, device_scale_factor=1)
        pg.goto((d / "preview.html").resolve().as_uri(), wait_until="networkidle")
        pg.evaluate("document.fonts.ready")
        pg.screenshot(path=str(d / "preview.png"))
        b.close()


def main(argv=None, root=EXAMPLES):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("names", nargs="*", help="examples to rebuild (default: all)")
    ap.add_argument("--check", action="store_true", help="rebuild in a temporary folder and fail on any difference; writes nothing")
    ap.add_argument("--png", action="store_true", help="also redraw preview.png with Playwright and Chrome")
    a = ap.parse_args(argv)
    if a.check and a.png:
        ap.error("--png writes preview.png; run it without --check")
    stale = []
    with tempfile.TemporaryDirectory(prefix="od-examples-") as tmp:
        for name in examples(root, a.names):
            built = Path(tmp) / name
            try:
                rebuild(root / name, built)
            except RuntimeError as e:
                print(e, file=sys.stderr)
                return 1
            if a.png:
                png(built)
            if a.check:
                changed, added, removed = compare(root / name, built)
            else:
                changed, added, removed = sync(root / name, built)
            for verb, rels in (("differs", changed), ("is new", added), ("is no longer made", removed)):
                stale += [f"examples/{name}/{r} {verb}" for r in rels]
            print(f"{name}: " + (f"{len(changed)} changed, {len(added)} new, {len(removed)} removed" if changed or added or removed
                                 else "matches the engine"))
    if a.check and stale:
        print("\n".join(stale))
        print(f"{len(stale)} file(s) in examples/ are not what the engine makes now. Run: python3 tools/build_examples.py")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())

def light_block(css):
    """Every declaration in the top-level :root blocks (not inside @media, not dark, not other densities)."""
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    depth, out = 0, []
    for m in re.finditer(r"([^{}]*)\{|\}", css):
        if m.group(0) == "}":
            depth -= 1
            continue
        sel = m.group(1).strip()
        if depth == 0 and sel.startswith(":root") and "dark" not in sel:
            end = css.index("}", m.end())
            out.append(css[m.end():end])
        depth += 1
    return "".join(out)


def build(look):
    """Run the look's recipe in a temporary folder; return its tokens.css."""
    with tempfile.TemporaryDirectory() as d:
        for cmd in look["recipe"]:
            subprocess.run([sys.executable, str(ENGINE), *cmd], cwd=d, check=True, capture_output=True)
        out = subprocess.run([sys.executable, str(ENGINE), "build"], cwd=d, check=True, capture_output=True, text=True).stdout
        if "Passes" not in out:
            raise SystemExit(f"{look['name']}: build did not pass\n{out}")
        return (pathlib.Path(d) / "opendesigner/build/css/tokens.css").read_text()


def known(feel):
    """Keep only the feel words the engine understands (engine.py feel), so a copied recipe never starts with a question."""
    keep = []
    for w in feel.split(","):
        out = subprocess.run([sys.executable, str(ENGINE), "feel", w], capture_output=True, text=True).stdout
        if "not known" not in out:
            keep.append(w)
    return ",".join(keep)


def looks():
    out = []
    for ex in EXAMPLES:  # the home page's three products
        out.append({"key": ex["key"], "name": ex["name"], "plain": f"{ex['feel']}; {ex['making']}", "brand": ex["brand"], "style": None,
                    "recipe": [["sketch", "--name", ex["name"], "--audience", ex["audience"], "--platforms", ex["platforms"],
                                "--feel", known(ex["feel"].replace(" ", "")), "--brand", ex["brand"], "--surfaces", ex["surfaces"]]]})
    for s in STYLED:
        out.append({**{k: s[k] for k in ("key", "name", "plain", "brand", "style")},
                    "recipe": [["sketch", "--name", s["name"], "--audience", s["audience"], "--platforms", "web", "--feel", known(s["feel"]), "--brand", s["brand"]],
                               ["pick", "Q-dir-01", s["style"]]]})
    return out


def main():
    parts = ["/* Generated by site/library_systems.py from the engine; do not edit. Each look, scoped to .odl-sys-<key>. */"]
    meta = []
    for look in looks():
        css = build(look)
        decls = re.findall(r"(--ds-[a-z0-9-]+\s*:[^;]+;)", light_block(css))
        parts.append(f".odl-sys-{look['key']} {{\n  " + "\n  ".join(decls) + "\n}")
        for q, inner in re.findall(r"@media \((pointer: [a-z]+)\) \{\s*:root \{([^}]*)\}", css):  # target sizes follow the pointer
            parts.append(f"@media ({q}) {{ .odl-sys-{look['key']} {{{inner}}} }}")
        meta.append({**look, "commands": ["engine.py " + " ".join(f'"{a}"' if " " in a or a.startswith("#") else a for a in cmd) for cmd in look["recipe"]]})
    OUT.write_text("\n".join(parts) + "\n")
    OUT_JSON.write_text(json.dumps(meta, indent=1) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)} and {OUT_JSON.relative_to(ROOT)}: " + ", ".join(m["name"] for m in meta))


if __name__ == "__main__":
    main()

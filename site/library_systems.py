#!/usr/bin/env python3
"""Make the looks the component library shop shows its components in, with the real engine, each scoped to a class
(.odl-sys-<key>) so one page can switch between them. Each look keeps its recipe (the engine commands that make it),
which the shop's kit turns into a design-system prompt.

  python3 site/library_systems.py      writes site/static/library-systems.css and site/library-looks.json

Light theme and default density only, like the site. Run it after engine changes, then rebuild the site.
"""
import json
import pathlib
import re
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "site"))
from demo_systems import ENGINE, EXAMPLES  # noqa: E402  (the landing page's three examples are looks too)

OUT = ROOT / "site/static/library-systems.css"
OUT_JSON = ROOT / "site/library-looks.json"
# Named styles from references/styles.json (core-ui fit), each with a brand colour and plain words. Every brand colour here is
# picked for the look, not taken from any real brand.

def primitives_data():
    cp = flat("color.primitives.tokens.json")
    colors = [[fig(p), t["$value"]["hex"]] for p, t in cp.items()]
    sp = flat("spacing.tokens.json")
    space = [[fig(p), t["$value"]["value"]] for p, t in sp.items()
             if p.startswith("space.") and isinstance(t["$value"], dict) and p.count(".") == 1]
    rd = flat("radius.tokens.json")
    radius = [[fig(p), t["$value"]["value"]] for p, t in rd.items() if p.startswith("radius.") and isinstance(t["$value"], dict)]
    bw = [[fig(p), t["$value"]["value"]] for p, t in rd.items() if p.startswith("border.width.") and isinstance(t["$value"], dict)]
    mo = flat("motion.tokens.json")
    dur = [[fig(p), t["$value"]["value"] / 1000] for p, t in mo.items()
           if p.startswith("motion.duration.") and isinstance(t["$value"], dict)]
    return {"colors": colors, "floats": space + radius + bw, "durations": dur}


SCOPES = [
    ("color/surface/", ["FRAME_FILL", "SHAPE_FILL"]), ("color/bg/", ["FRAME_FILL", "SHAPE_FILL"]),
    ("color/text/", ["TEXT_FILL"]), ("color/icon/", ["SHAPE_FILL", "STROKE_COLOR"]),
    ("color/border/", ["STROKE_COLOR"]), ("color/overlay/", ["FRAME_FILL"]), ("color/shadow/", ["EFFECT_COLOR"]),
]


def scopes_for(name):
    for prefix, sc in SCOPES:
        if name.startswith(prefix):
            return sc
    raise KeyError(name)


def color_data():
    light, dark = flat("color.light.tokens.json"), flat("color.dark.tokens.json")
    rows = []
    for p, t in light.items():
        lv, dv = t["$value"], dark[p]["$value"]
        enc = lambda v: {"alias": alias_target(v)} if alias_target(v) else {"hex": v["hex"], "a": v.get("alpha", 1)}
        rows.append([fig(p), enc(lv), enc(dv), scopes_for(fig(p)), t["$description"]])
    return rows


def spacing_radius_data():
    comfy, compact = flat("spacing.comfortable.tokens.json"), flat("spacing.compact.tokens.json")
    sp, rd = flat("spacing.tokens.json"), flat("radius.tokens.json")
    spacing = [[fig(p), alias_target(t["$value"]), alias_target(compact[p]["$value"]), ["GAP"], t.get("$description", "")] for p, t in comfy.items()]
    for p, t in sp.items():
        if p.startswith("space.layout."):
            spacing.append([fig(p), alias_target(t["$value"]), alias_target(t["$value"]), ["GAP"], t["$description"]])
        elif p.startswith("size."):
            spacing.append([fig(p), {"value": t["$value"]["value"]}, {"value": t["$value"]["value"]}, ["WIDTH_HEIGHT"], t.get("$description", "")])
    radius = []
    for p, t in rd.items():
        v = t["$value"]
        if p.startswith("radius.") and (alias_target(v) or p == "radius.full"):
            radius.append([fig(p), alias_target(v) or fig(p), ["CORNER_RADIUS"], t.get("$description", "")])
        elif p.startswith("border.width.") and alias_target(v):
            radius.append([fig(p), alias_target(v), ["STROKE_FLOAT"], t.get("$description", "")])
        elif p.startswith("focus.ring."):
            radius.append([fig(p), alias_target(v) if alias_target(v) else {"value": v["value"]}, ["STROKE_FLOAT", "EFFECT_FLOAT"], ""])
    return {"spacing": spacing, "radius": radius}


def typography_data():
    ty = flat("typography.tokens.json")
    fam = {"font/family/sans": "Inter", "font/family/mono": "JetBrains Mono"}
    floats = [[fig(p), t["$value"] if isinstance(t["$value"], (int, float)) else t["$value"]["value"],
               {"weight": "FONT_WEIGHT", "size": "FONT_SIZE", "lineHeight": "LINE_HEIGHT"}[p.split(".")[1]]]
              for p, t in ty.items() if p.startswith("font.") and not p.startswith("font.family")]
    styles = []
    r = resolve()
    for p, t in ty.items():
        if not p.startswith("text."):
            continue
        ext = t["$extensions"][NS]
        v = r[p]["resolved"]
        styles.append({"name": fig(p), "family": "mono" if "JetBrains Mono" in v["fontFamily"] else "sans",
                       "weight": v["fontWeight"], "size": fig(ext["fontSizeRef"]), "line": fig(ext["lineHeightRef"]),
                       "tracking": v["letterSpacing"]["value"], "upper": ext.get("textTransform") == "uppercase",
                       "description": f"Use: {ext['use']} Avoid: {ext['avoid']}"})
    return {"families": [[k, v] for k, v in fam.items()], "floats": floats, "styles": styles}


def motion_data():
    mo, std, red = flat("motion.tokens.json"), flat("motion.standard.tokens.json"), flat("motion.reduced.tokens.json")
    durations = [[fig(p), alias_target(t["$value"])] for p, t in mo.items() if p.startswith("motion.duration.") and alias_target(t["$value"])]
    easings = [[fig(p), "cubic-bezier(" + ", ".join(f"{x:g}" for x in t["$value"]) + ")", t["$description"]]
               for p, t in mo.items() if p.startswith("motion.easing.")]
    transitions = []
    for p, t in std.items():
        s, rr = t["$value"], red[p]["$value"]
        transitions.append([fig(p), alias_target(s["duration"]), alias_target(rr["duration"]),
                            alias_target(s["timingFunction"]), alias_target(rr["timingFunction"])])
    return {"durations": durations, "easings": dict((e[0], e[1]) for e in easings), "easingRows": easings, "transitions": transitions}


def effects_data():
    el = flat("elevation.tokens.json")
    out = []
    for p, t in el.items():
        layers = [{"color": alias_target(l["color"]), "x": l["offsetX"]["value"], "y": l["offsetY"]["value"],
                   "blur": l["blur"]["value"], "spread": l["spread"]["value"]} for l in t["$value"]]
        out.append({"name": fig(p), "layers": layers, "description": t["$description"]})
    out.append({"name": "focus/ring", "description": "Focus-visible ring: 2px gap in the surface color, then a 2px border.focus ring (DC-L04-09).",
                "layers": [{"color": "color/surface/raised", "x": 0, "y": 0, "blur": 0, "spread": 2},
                           {"color": "color/border/focus", "x": 0, "y": 0, "blur": 0, "spread": 4}]})
    return out



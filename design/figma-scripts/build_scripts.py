#!/usr/bin/env python3
"""Generate the ordered use_figma scripts (and Paper token list) from design/tokens (stdlib only).

    python3 design/figma-scripts/build_scripts.py

Each NN-*.js file is the `code` argument for one `use_figma` call. Scripts follow Figma's figma-use
rules (fetched 2026-09-23): plain JS, top-level await, `return` for output, no IIFE, explicit scopes,
one page switch per call, and every created/mutated id returned. Every script is idempotent: it finds
collections, variables, styles and components by name and updates them instead of duplicating.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TOK = os.path.join(HERE, "..", "tokens")
sys.path.insert(0, TOK)
from check_contrast import _flatten, _load, resolve  # noqa: E402

NS = "dev.dsbuilder"


def flat(name):
    out = {}
    _flatten(_load(name), "", None, out)
    return out


def fig(path):
    return path.replace(".", "/")


def alias_target(v):
    return fig(v[1:-1]) if isinstance(v, str) and v.startswith("{") else None


PRELUDE = r"""// ---- shared prelude (identical in every step) ----
const hex = (h) => ({ r: parseInt(h.slice(1, 3), 16) / 255, g: parseInt(h.slice(3, 5), 16) / 255, b: parseInt(h.slice(5, 7), 16) / 255 });
const rgba = (h, a) => Object.assign(hex(h), { a: a === undefined ? 1 : a });
const collections = await figma.variables.getLocalVariableCollectionsAsync();
const allVars = await figma.variables.getLocalVariablesAsync();
const report = { created: [], updated: [], warnings: [] };
function ensureCollection(name, modeNames) {
  let c = collections.find((x) => x.name === name);
  if (!c) { c = figma.variables.createVariableCollection(name); collections.push(c); report.created.push(c.id); }
  modeNames.forEach((m, i) => {
    if (i < c.modes.length) { if (c.modes[i].name !== m) c.renameMode(c.modes[i].modeId, m); }
    else { try { c.addMode(m); } catch (e) { report.warnings.push(`addMode ${name}/${m}: ${e.message} (plan without modes?)`); } }
  });
  return c;
}
const modeId = (c, name) => (c.modes.find((m) => m.name === name) || c.modes[0]).modeId;
function ensureVar(c, name, type) {
  let v = allVars.find((x) => x.variableCollectionId === c.id && x.name === name);
  if (v && v.resolvedType !== type) throw new Error(`type clash on ${name}: ${v.resolvedType} vs ${type}`);
  if (!v) { v = figma.variables.createVariable(name, c, type); allVars.push(v); report.created.push(v.id); }
  else report.updated.push(v.id);
  return v;
}
function findVar(collectionName, name) {
  const c = collections.find((x) => x.name === collectionName);
  const v = c && allVars.find((x) => x.variableCollectionId === c.id && x.name === name);
  if (!v) throw new Error(`missing variable ${collectionName} / ${name}: run the earlier step first`);
  return v;
}
const alias = (v) => ({ type: 'VARIABLE_ALIAS', id: v.id });
const camel = (parts) => parts.map((p, i) => (i === 0 ? p : p.charAt(0).toUpperCase() + p.slice(1))).join('');
function codeSyntax(v) {
  const parts = v.name.split('/');
  const ns = 'DS' + parts[0].charAt(0).toUpperCase() + parts[0].slice(1);
  v.setVariableCodeSyntax('WEB', `var(--${parts.join('-')})`);
  v.setVariableCodeSyntax('ANDROID', `${ns}.${camel(parts.slice(1))}`);
  v.setVariableCodeSyntax('iOS', `${ns}.${camel(parts.slice(1))}`);
}
// ---- end prelude ----
"""


def script(num, title, doc, data, body):
    head = f"// {num} · {title}\n// {doc}\n// Generated by design/figma-scripts/build_scripts.py from design/tokens. Do not edit by hand.\n"
    data_js = "" if data is None else f"const DATA = {json.dumps(data, separators=(',', ':'))};\n"
    return head + PRELUDE + data_js + body.strip() + "\n"


